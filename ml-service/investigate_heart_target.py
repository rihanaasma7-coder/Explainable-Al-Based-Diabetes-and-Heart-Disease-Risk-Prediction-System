import os
import pandas as pd
path = os.path.join('..','datasets','heart_disease.csv')
df = pd.read_csv(path)
print('columns:', df.columns.tolist())
print('target counts:', df['target'].value_counts().to_dict())
print('\ncp mean by target:')
print(df.groupby('target')['cp'].mean())
print('\nthalach mean by target:')
print(df.groupby('target')['thalach'].mean())
print('\nchol mean by target:')
print(df.groupby('target')['chol'].mean())
print('\ntrestbps mean by target:')
print(df.groupby('target')['trestbps'].mean())
print('\nfbs mean by target:')
print(df.groupby('target')['fbs'].mean())
print('\nrestecg mean by target:')
print(df.groupby('target')['restecg'].mean())
print('\nthalfrequencies:')
print(pd.crosstab(df['target'], df['thal']))
print('\ncp frequencies:')
print(pd.crosstab(df['target'], df['cp']))
print('\nSample rows target=0:')
print(df[df['target']==0].head(10).to_string(index=False))
print('\nSample rows target=1:')
print(df[df['target']==1].head(10).to_string(index=False))
